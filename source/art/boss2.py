import numpy as np, math, sys
from PIL import Image, ImageDraw
S = 96
L = np.array([-0.55, -0.65, 0.52]); L = L / np.linalg.norm(L)
OUT = (22, 12, 28)

def ramp(c, warm=(0, 0, 0)):
    c = np.array(c, float)
    return [np.clip(c * 0.42 + np.array([0, 0, 18]), 0, 255), np.clip(c * 0.68, 0, 255), c, np.clip(c * 1.22 + 14 + np.array(warm), 0, 255), np.clip(c * 1.5 + 40 + np.array(warm), 0, 255)]

class Cv:
    def __init__(s):
        s.a = np.zeros((S, S, 4), float)
    def _put(s, m, lum, col, warm=(0, 0, 0)):
        r = ramp(col, warm)
        idx = np.clip((lum * 5).astype(int), 0, 4)
        for i in range(5):
            mm = m & (idx == i)
            s.a[mm, :3] = r[i]; s.a[mm, 3] = 255
    def ell(s, cx, cy, rx, ry, col, warm=(0, 0, 0), tex=0.0):
        y, x = np.mgrid[0:S, 0:S].astype(float)
        nx = (x + .5 - cx) / rx; ny = (y + .5 - cy) / ry; d = nx * nx + ny * ny; m = d <= 1
        nz = np.sqrt(np.clip(1 - d, 0, 1)); lum = np.clip(nx * L[0] + ny * L[1] + nz * L[2], 0, 1)
        lum = 0.12 + 0.88 * lum
        if tex: lum = np.clip(lum + (np.random.RandomState(int(cx * 7 + cy)).rand(S, S) - .5) * tex, 0, .999)
        s._put(m, np.clip(lum, 0, .999), col, warm)
    def cap(s, x0, y0, x1, y1, r0, r1, col, warm=(0, 0, 0)):
        y, x = np.mgrid[0:S, 0:S].astype(float); x += .5; y += .5
        vx, vy = x1 - x0, y1 - y0; ll = vx * vx + vy * vy + 1e-9
        t = np.clip(((x - x0) * vx + (y - y0) * vy) / ll, 0, 1); px, py = x0 + t * vx, y0 + t * vy
        r = r0 + (r1 - r0) * t; dx, dy = x - px, y - py; dist = np.sqrt(dx * dx + dy * dy); m = dist <= r
        nx = dx / r; ny = dy / r; nz = np.sqrt(np.clip(1 - nx * nx - ny * ny, 0, 1))
        lum = 0.12 + 0.88 * np.clip(nx * L[0] + ny * L[1] + nz * L[2], 0, 1)
        s._put(m, np.clip(lum, 0, .999), col, warm)
    def poly(s, pts, col, warm=(0, 0, 0), flat=False, dirv=(-1, -1)):
        im = Image.new("L", (S, S), 0); ImageDraw.Draw(im).polygon([tuple(p) for p in pts], fill=255)
        m = np.array(im) > 127
        y, x = np.mgrid[0:S, 0:S].astype(float)
        xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
        g = ((x - min(xs)) * dirv[0] + (y - min(ys)) * dirv[1]); g = (g - g[m].min()) / (np.ptp(g[m]) + 1e-6) if m.any() else g
        lum = 0.2 + 0.7 * (1 - g) if not flat else np.full((S, S), 0.5)
        s._put(m, np.clip(lum, 0, .999), col, warm)
    def dot(s, x, y, col, w=1, h=1):
        s.a[int(y):int(y) + h, int(x):int(x) + w, :3] = col; s.a[int(y):int(y) + h, int(x):int(x) + w, 3] = 255
    def glow(s, cx, cy, r, col, k=.8):
        y, x = np.mgrid[0:S, 0:S].astype(float); d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2); f = np.clip(1 - d / r, 0, 1) ** 1.6 * k
        m = s.a[..., 3] > 0
        for c in range(3): s.a[..., c] = np.where(m, s.a[..., c] * (1 - f) + col[c] * f, s.a[..., c])
    def rim(s):
        a = s.a[..., 3] > 0; up = np.zeros_like(a); up[1:] = a[:-1]
        edge = a & ~up  # 위쪽이 비어있는 픽셀 = 윗 테두리
        s.a[edge, :3] = np.clip(s.a[edge, :3] * 1.25 + 25, 0, 255)
    def outline(s, col=OUT):
        a = s.a[..., 3] > 0; o = np.zeros_like(a)
        o[1:] |= a[:-1]; o[:-1] |= a[1:]; o[:, 1:] |= a[:, :-1]; o[:, :-1] |= a[:, 1:]
        o &= ~a; s.a[o, :3] = col; s.a[o, 3] = 255
    def shadow(s):
        y, x = np.mgrid[0:S, 0:S].astype(float); d = ((x - 48) / 30) ** 2 + ((y - 91) / 3.2) ** 2; m = (d <= 1) & (s.a[..., 3] == 0)
        s.a[m, :3] = (10, 8, 16); s.a[m, 3] = 120
    def img(s):
        s.shadow(); s.rim(); s.outline(); return Image.fromarray(s.a.clip(0, 255).astype(np.uint8), "RGBA")

def eyes(c, pts, col=(255, 236, 90), glow=True):
    for (x, y) in pts:
        c.dot(x - 1, y, col, 3, 2)
        c.dot(x, y, (40, 8, 12), 1, 2)

