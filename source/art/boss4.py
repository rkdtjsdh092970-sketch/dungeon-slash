def bolt(c, x, y, ang, ln, col, w=2, seed=1, seg=5, jit=6, core=None):
    r = np.random.RandomState(seed); px_, py_ = x, y; step = ln / seg; pts = []
    for i in range(seg):
        a = ang + r.uniform(-0.7, 0.7); nx_, ny_ = px_ + math.cos(a) * step + r.uniform(-jit, jit) * .3, py_ + math.sin(a) * step
        pts.append((px_, py_, nx_, ny_)); px_, py_ = nx_, ny_
    for (a_, b_, c_, d_) in pts: c.line(a_, b_, c_, d_, col, w)
    if core:
        for (a_, b_, c_, d_) in pts: c.line(a_, b_, c_, d_, core, max(1, w - 2))

