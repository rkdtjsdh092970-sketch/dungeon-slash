import numpy as np, math, sys
from PIL import Image, ImageDraw
S = 96
OUT = (20, 10, 26)

def shift(m, dx, dy):
    r = np.zeros_like(m)
    ys = slice(max(dy, 0), S + min(dy, 0)); yd = slice(max(-dy, 0), S + min(-dy, 0))
    xs = slice(max(dx, 0), S + min(dx, 0)); xd = slice(max(-dx, 0), S + min(-dx, 0))
    r[ys, xs] = m[yd, xd]; return r

def mul(c, f, add=(0, 0, 0)): return tuple(int(max(0, min(255, c[i] * f + add[i]))) for i in range(3))

class Cv:
    def __init__(s):
        s.a = np.zeros((S, S, 4), np.uint8); s.glows = []
    def mask_poly(s, pts):
        im = Image.new("L", (S, S), 0); ImageDraw.Draw(im).polygon([tuple(p) for p in pts], fill=255); return np.array(im) > 127
    def mask_ell(s, cx, cy, rx, ry):
        y, x = np.mgrid[0:S, 0:S]; return ((x + .5 - cx) / rx) ** 2 + ((y + .5 - cy) / ry) ** 2 <= 1
    def mask_line(s, x0, y0, x1, y1, w):
        im = Image.new("L", (S, S), 0); ImageDraw.Draw(im).line([(x0, y0), (x1, y1)], fill=255, width=w); return np.array(im) > 127
    def fill(s, m, col, cel=True, edge=0.38, rim=True, sh=True):
        if m is None or not m.any(): return
        a = s.a; a[m, :3] = col; a[m, 3] = 255
        if cel:
            hi = m & ~shift(m, 2, 2); lo = m & ~shift(m, -3, -3)
            if sh: a[lo, :3] = mul(col, 0.62, (0, 0, 14))
            if rim: a[hi, :3] = mul(col, 1.28, (14, 14, 8))
        er = m & ~(shift(m, 1, 0) & shift(m, -1, 0) & shift(m, 0, 1) & shift(m, 0, -1))
        if edge: a[er, :3] = mul(col, edge)
    def poly(s, pts, col, **k): s.fill(s.mask_poly(pts), col, **k)
    def ell(s, cx, cy, rx, ry, col, **k): s.fill(s.mask_ell(cx, cy, rx, ry), col, **k)
    def limb(s, x0, y0, x1, y1, w0, w1, col, **k):
        dx, dy = x1 - x0, y1 - y0; l = math.hypot(dx, dy) + 1e-6; nx, ny = -dy / l, dx / l
        s.poly([(x0 + nx * w0, y0 + ny * w0), (x1 + nx * w1, y1 + ny * w1), (x1 - nx * w1, y1 - ny * w1), (x0 - nx * w0, y0 - ny * w0)], col, **k)
        s.ell(x0, y0, w0, w0, col, **k); s.ell(x1, y1, w1, w1, col, **k)
    def line(s, x0, y0, x1, y1, col, w=1):
        s.fill(s.mask_line(x0, y0, x1, y1, w), col, cel=False, edge=0)
    def px(s, x, y, col, w=1, h=1):
        s.a[int(y):int(y) + h, int(x):int(x) + w, :3] = col; s.a[int(y):int(y) + h, int(x):int(x) + w, 3] = 255
    def glow(s, cx, cy, r, col, k=.6):
        y, x = np.mgrid[0:S, 0:S].astype(float); d = np.sqrt((x - cx) ** 2 + (y - cy) ** 2); f = np.clip(1 - d / r, 0, 1) ** 2 * k
        m = s.a[..., 3] > 0
        for c in range(3): s.a[..., c] = np.where(m, s.a[..., c] * (1 - f) + col[c] * f, s.a[..., c])
    def eye(s, x, y, col=(255, 230, 80), w=4):
        s.px(x - w // 2, y, (20, 8, 14), w, 2); s.px(x - w // 2 + 1, y, col, w - 2, 1); s.px(x - w // 2 + 1, y + 1, mul(col, .6), w - 2, 1)
    def spike(s, x, y, ang, ln, wd, col):
        tx, ty = x + math.cos(ang) * ln, y + math.sin(ang) * ln; nx, ny = -math.sin(ang) * wd, math.cos(ang) * wd
        s.poly([(x + nx, y + ny), (tx, ty), (x - nx, y - ny)], col)
    def stipple(s, m, col, dens, seed=1):
        r = np.random.RandomState(seed).rand(S, S) < dens; mm = m & r & (s.a[..., 3] > 0); s.a[mm, :3] = col
    def finish(s):
        a = s.a[..., 3] > 0; o = np.zeros_like(a)
        o[1:] |= a[:-1]; o[:-1] |= a[1:]; o[:, 1:] |= a[:, :-1]; o[:, :-1] |= a[:, 1:]; o &= ~a
        s.a[o, :3] = OUT; s.a[o, 3] = 255
        y, x = np.mgrid[0:S, 0:S].astype(float); d = ((x - 48) / 32) ** 2 + ((y - 91) / 3.4) ** 2; m = (d <= 1) & (s.a[..., 3] == 0)
        s.a[m, :3] = (8, 6, 14); s.a[m, 3] = 110
        return Image.fromarray(s.a, "RGBA")

