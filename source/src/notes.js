const NB = { sel: 0 };
function notesUnread() { return !!(save && PATCH_NOTES.length && save.notesSeen !== PATCH_NOTES[0].ver); }
function openNotes() {
  if (save) { save.notesSeen = PATCH_NOTES[0].ver; saveGame(); }
  const n = PATCH_NOTES[Math.min(NB.sel, PATCH_NOTES.length - 1)];
  Modal.open(`<h2>📜 업데이트 게시판</h2><div class="nb"><div class="nb-list">${PATCH_NOTES.map((p, i) => `<div class="nb-it ${i === NB.sel ? "on" : ""}" data-a="nbpick" data-i="${i}"><b>v${p.ver}</b>${i === 0 ? `<em>최신</em>` : ""}<small>${p.date}</small><div>${p.title}</div></div>`).join("")}</div>
    <div class="nb-body"><div class="nb-h"><b>v${n.ver}</b> <span>${n.date}</span></div><div class="nb-t">${n.title}</div><ul>${n.items.map((x) => `<li>${x}</li>`).join("")}</ul></div></div>
    <div class="dim center" style="margin-top:6px">현재 빌드 ${typeof BUILD_ID === "string" ? BUILD_ID : ""}</div>`, { cls: "wide", on: { nbpick: (el) => { NB.sel = +el.dataset.i; snd("click"); openNotes(); } } });
  refreshTop();
}
